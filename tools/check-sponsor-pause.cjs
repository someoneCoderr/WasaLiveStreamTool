// Exercise the production scheduler without a server or a vMix connection.
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const Module = require('node:module');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const filename = path.join(root, 'dist/server.cjs');
const source = fs.readFileSync(filename, 'utf8').replace(/\r\n/g, '\n');
const marker = '// server/index.ts\nvar ROOT';
assert.equal(source.split(marker).length, 2);
const isolated = new Module(filename, module);
isolated.filename = filename;
isolated.paths = module.paths;
isolated._compile(source.split(marker)[0] + '\nmodule.exports = { Sponsors, Panel, loadConfig };', filename);
const {Sponsors, Panel, loadConfig} = isolated.exports;
const cfg = loadConfig(root);
const sent = [];
const scheduler = new Sponsors({...cfg.sponsor, list: [], order: []}, async command => sent.push(command), x => x, null);
let now = 100000;
const originalNow = Date.now;
const flush = () => new Promise(resolve => setImmediate(resolve));
(async () => {
  Date.now = () => now;
  scheduler.setAuto(true);
  now += 178000;
  scheduler.tick(now, true, false);
  await flush();
  assert.equal(sent.length, 0, 'No automatic overlay when the pause starts at the due time');
  assert.equal(scheduler.enabled, true, 'Pause must preserve the operator auto switch');
  now += 15 * 60000;
  scheduler.tick(now, true, true);
  await flush();
  assert(sent.some(c => c.Function === 'OverlayInput3Out'), 'Already visible sponsor must be hidden');
  assert(!sent.some(c => c.Function === 'OverlayInput3In'));
  scheduler.tick(now, false, false);
  await flush();
  assert(!sent.some(c => c.Function === 'OverlayInput3In'), 'No overdue sponsor immediately after a pause');
  now += 178000;
  scheduler.tick(now, false, false);
  await flush();
  assert(sent.some(c => c.Function === 'OverlayInput3In'), 'Auto rotation must resume after the full interval');
  // A pending automatic fade-in must not sneak past the pause guard.
  const delayed = [];
  const loading = new Sponsors({...cfg.sponsor, list: [{label:'Test', title:'Test', picture:'test.png'}], order: [1]}, async c => delayed.push(c), x => x, null);
  const pending = loading.show();
  loading.tick(now, true, false);
  await pending;
  assert(!delayed.some(c => c.Function === 'OverlayInput3In'));
  const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'wasa-sponsor-test-'));
  const panel = new Panel(cfg, {call: async () => {}}, scratch);
  const breakKey = cfg.audio.breakVideo;
  const camera = {number:1, key:'main', title:'CAM1', layers:[]};
  const ads = {number:27, key:breakKey, title:'List', layers:[]};
  const frame = {number:28, key:'frame', title:'Pausenwerbung WASA', layers:[breakKey]};
  panel.vm = {inputs:[camera, ads, frame], active:1};
  panel.schedule.running = {pause:true};
  assert.equal(panel.sponsorBlocked(), true, 'Pause status blocks sponsors even on a camera shot');
  panel.schedule.running.pause = false;
  assert.equal(panel.sponsorBlocked(), false, 'Stored pause screen alone must not block the game');
  panel.vm.active = 28;
  assert.equal(panel.sponsorBlocked(), true, 'Layered WASA advertising picture blocks sponsors');
  panel.vm.active = 27;
  assert.equal(panel.sponsorBlocked(), true, 'Direct advertising list blocks sponsors');
  panel.vm.active = 1;
  panel.sequences = 1;
  assert.equal(panel.sponsorBlocked(), true, 'Lidl return sequence remains blocked');
  console.log('OK: no sponsors during pause or advertising, visible sponsors hidden, no catch-up after pause, automatic resume, pending image race guarded.');
})().catch(e => {console.error(e); process.exitCode = 1;}).finally(() => {Date.now = originalNow;});
